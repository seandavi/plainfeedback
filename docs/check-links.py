"""Check internal links and #anchors in the rendered site. Usage: python3 check-links.py [_site]

`quarto render` warns about a missing target file but never about a missing anchor, and
pandoc's heading ids differ from GitHub's, so cross-page anchors can break silently.
"""

import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

site = Path(sys.argv[1] if len(sys.argv) > 1 else "_site").resolve()
ids = {}  # page -> set of ids, read lazily
bad = []


def page_ids(p: Path) -> set:
    if p not in ids:
        ids[p] = set(re.findall(r'\bid="([^"]+)"', p.read_text(errors="replace")))
    return ids[p]


for page in site.rglob("*.html"):
    html = page.read_text(errors="replace")
    # Only the page body: navbar/sidebar/footer links are generated by Quarto.
    m = re.search(r'<main[^>]*>(.*)</main>', html, re.S)
    for href in re.findall(r'href="([^"]+)"', m.group(1) if m else ""):
        u = urlsplit(href)
        if u.scheme or u.netloc or href.startswith("mailto:"):
            continue
        target = (page.parent / unquote(u.path)).resolve() if u.path else page
        if target.is_dir():
            target = target / "index.html"
        if not target.exists():
            bad.append(f"{page.relative_to(site)}: missing {href}")
        elif u.fragment and target.suffix == ".html" and u.fragment not in page_ids(target):
            bad.append(f"{page.relative_to(site)}: no #{u.fragment} in {href}")

print("\n".join(bad) or "links: clean")
sys.exit(1 if bad else 0)
